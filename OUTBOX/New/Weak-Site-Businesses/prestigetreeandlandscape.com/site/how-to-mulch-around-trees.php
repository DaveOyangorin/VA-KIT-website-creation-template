<section class="sec"><div class="wrap sv-grid"><article class="prose"><p class="answer">Spread 2 to 4 inches of organic mulch, such as wood chips or bark, in a wide ring around the tree, out to the edge of its crown if you can. Keep it pulled back several inches from the trunk so the root flare shows. Never pile it into a cone against the bark: &ldquo;mulch volcanoes&rdquo; trap moisture, invite disease and rodents, and can cause roots to girdle the trunk.</p>

<p>Mulch is one of the cheapest, most effective things you can do for a tree, and one of the easiest to get wrong. Tall cones of fresh bark around a trunk may look tidy, but they can slowly hurt the tree. Here is what the International Society of Arboriculture (ISA), the body that certifies arborists, and the USDA Forest Service say about doing it right.</p>

<h2>Why mulch helps</h2>
<p>ISA calls mulching one of the most beneficial practices a homeowner can use for tree health. Its list of benefits:</p>
<ul>
<li>Reduces soil moisture loss through evaporation</li>
<li>Helps control weed germination and growth</li>
<li>Insulates the soil, protecting roots from extreme summer and winter temperatures</li>
<li>Can improve soil biology, aeration, structure and drainage over time</li>
<li>Can improve soil fertility as some mulches decompose</li>
<li>Inhibits certain plant diseases</li>
<li>Keeps string trimmers and mowers away from the trunk</li>
</ul>
<p>The USDA Forest Service article by research tree physiologist Jerry Van Sambeek adds the research behind it: trees and shrubs grow faster when mulched with organic mulches than when the ground beneath them is kept bare, and mulch moderates soil temperatures, keeping soil cooler in summer and warmer in winter. He notes tree roots commonly die at soil temperatures above 90&deg;F or below 20&deg;F, which makes that buffering especially useful in a climate with Utah&rsquo;s summer heat and winter cold.</p>

<h2>How deep: 2 to 4 inches</h2>
<p>ISA&rsquo;s generally recommended depth is <strong>2 to 4 inches</strong>. On well-drained sites, apply 2 to 4 inches; use less where drainage is poor. Coarse mulches can go slightly deeper without harm. The Forest Service article, citing an ISA-certified arborist, suggests 2 to 3 inches for most plants and garden beds, an extra inch on sandy soil, and a bit less around shallow-rooted shrubs.</p>
<p>More is not better. ISA warns that many landscapes are falling victim to a plague of overmulching, often because new mulch is added every year just to refresh the color, faster than the old layer decomposes. If there&rsquo;s already enough, ISA&rsquo;s advice is to break up any matted layer and freshen it with a rake instead.</p>

<h2>How wide: the bigger the ring, the better</h2>
<p>ISA says to place mulch out to the edge of the tree&rsquo;s crown or beyond, noting that if a tree had a say, its entire root system, which usually extends well beyond the drip line, would be mulched. The Forest Service article agrees: the larger the mulch ring, the greater the benefit to the tree. For a newly planted seedling it suggests a circle about 4 feet across.</p>

<h2>Keep it off the trunk</h2>
<p>This is the rule that matters most. The Forest Service article says mulch should be pulled <strong>at least 2 to 6 inches away from the trunk, stem or root flare</strong>, so the bark stays dry and less vulnerable to infection by root and stem diseases, and to deny cover to mice and voles, which do most of their damage in winter. ISA&rsquo;s version: if mulch is piled against the trunk, pull it back several inches so the base of the trunk is exposed.</p>
<p>The root flare is the place where the trunk widens as it meets the roots. If you can&rsquo;t see it, the mulch or soil is too deep.</p>

<h2>Why mulch volcanoes do damage</h2>
<p>A &ldquo;volcano&rdquo; is mulch piled deeper at the trunk than out at the drip line. The Forest Service article quotes an ISA-certified arborist calling it &ldquo;one of the worst things you can do to a plant or tree,&rdquo; because it reduces air movement into the soil and prevents deep roots from growing. ISA lists the problems that come with overmulching:</p>
<ul>
<li>On wet soils, deep mulch can keep the root zone too wet, stressing the plant and causing root rot.</li>
<li>Mulch piled against the trunk can stress stem tissue and lead to insect and disease problems, or to stem-girdling roots.</li>
<li>Thick blankets of fine mulch can mat down and reduce water and air penetration.</li>
<li>Mulch piled high against young trees can shelter rodents that chew the bark and can girdle the tree.</li>
<li>Anaerobic &ldquo;sour&rdquo; mulch can give off pungent odors and build up compounds that may be toxic to young plants.</li>
</ul>

<h2>Which mulch to use</h2>
<p>ISA divides mulches into inorganic (stone, lava rock, rubber, landscape fabric) and organic (wood chips, pine needles, bark, leaves, compost and similar plant-based products). Inorganic mulches last longer but don&rsquo;t improve the soil, so most horticulturists and arborists prefer organic mulches. ISA notes that composted wood chips make good mulch, especially with some bark and leaves mixed in, and that fresh chips can be used around established trees, but fine, non-composted chips should be avoided because they can tie up soil nitrogen as they break down.</p>
<p>The Forest Service article adds that fine materials like grass clippings should be mixed with coarser mulch so they don&rsquo;t pack down, and that plastic films and fabrics can block water and air.</p>

<h2>A five-minute mulch check</h2>
<ol>
<li><strong>Find the root flare.</strong> If it&rsquo;s buried, pull mulch back several inches from the trunk.</li>
<li><strong>Measure the depth</strong> with a finger or trowel. Aim for 2 to 4 inches, less on poorly drained soil.</li>
<li><strong>Widen the ring</strong> toward the drip line instead of piling higher.</li>
<li><strong>Break up matted layers</strong> before adding anything new.</li>
<li><strong>Top up only when needed</strong>, as the old layer breaks down.</li>
</ol>

