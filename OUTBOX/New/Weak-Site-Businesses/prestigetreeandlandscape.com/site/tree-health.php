<h2>Tree Insect Infestation and Tree Disease</h2>
<p>Caring for the health of trees includes regular evaluation for insect and disease. Insects can quickly and significantly damage a tree if left unchecked. A thinning canopy, small holes in the bark and discolored leaves are some of the indicators that the experienced staff at Prestige Tree And Landscape are trained to assess and identify. We have several disease and insect control options for serious threats such as Emerald Ash Borer and other tree ailments that pose a threat to your property.</p>
<h2>Tree Root Protection</h2>
<p>The source of many tree problems starts underground at the root. Poor growth, girdling of roots and other pest problems can often be traced back to a tree that was incorrectly planted in the first place. Removal of soil and mulch from the trunk area and professional root collar excavation are effective processes that a Prestige Tree And Landscape arborist can use to correct such problems. Specialized root pruning with advanced equipment is also an option for preserving optimal tree health.</p>
<h2>Soil Assessment</h2>
<p>Proper assessment of the soil at the roots of your trees on your property in Holladay is an environmentally sound approach to optimal tree care. Trees, shrubs and hedges are less vulnerable to damage from disease and adverse climate conditions when proper soil compaction and nutrient deficiencies are identified and rectified promptly.</p>
